def get_color_hex(color_code):
    """Get the hex color string for a given CEWE color code."""
    return COLOR_MAP.get(color_code, '#000000')  # Default to black if not found

def get_color_rgb(color_code):
    """Get the RGB tuple for a given CEWE color code."""
    hex_color = get_color_hex(color_code)
    hex_color = hex_color.lstrip('#')
    return tuple(int(hex_color[i:i+2], 16) for i in (0, 2, 4))

def getBackgroundAndFrameColour(background_id) -> tuple[str, str]:
    if background_id:
        try:
            bg_id_int = int(background_id)
            page_bg_color = get_color_hex(bg_id_int)
            # Use white frame for dark backgrounds (luminance < 128), black for light backgrounds
            # Simple luminance calculation from hex color
            hex_color = page_bg_color.lstrip('#')
            r, g, b = tuple(int(hex_color[i:i + 2], 16) for i in (0, 2, 4))
            luminance = 0.299 * r + 0.587 * g + 0.114 * b
            frame_color = 'white' if luminance < 128 else 'black'
        except (ValueError, TypeError):
            # Fallback to white background if ID is invalid
            page_bg_color = 'white'
            frame_color = 'black'
    else:
        # Default to white background if no ID specified
        page_bg_color = 'white'
        frame_color = 'black'
    return page_bg_color, frame_color